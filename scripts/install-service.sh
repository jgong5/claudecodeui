#!/usr/bin/env bash
# Install or update CloudCLI as the systemd service `cloudcli`, built from this checkout.
# Re-run to update; options given once are remembered in ~/.cloudcli/service.conf.
# Needs Linux, systemd and sudo.
set -euo pipefail

CONF=$HOME/.cloudcli/service.conf
ENV_FILE= PORT=3001 WORKSPACES_ROOT=$HOME
[[ -f $CONF ]] && source "$CONF"

usage() {
  cat <<EOF
Usage: $0 [--env-file PATH] [--port N] [--workspaces-root DIR]

  --env-file PATH         bash file sourced before start (API keys, ANTHROPIC_* vars)
  --port N                listen port (now: $PORT)
  --workspaces-root DIR   root for the folder picker and file tree (now: $WORKSPACES_ROOT)
EOF
}

while (($#)); do
  case $1 in
    --env-file) ENV_FILE=$(realpath "$2"); shift 2 ;;
    --port) PORT=$2; shift 2 ;;
    --workspaces-root) WORKSPACES_ROOT=$(realpath "$2"); shift 2 ;;
    -h|--help) usage; exit ;;
    *) usage >&2; exit 1 ;;
  esac
done
[[ $PORT =~ ^[0-9]+$ ]] || { echo "--port needs a number, got: $PORT" >&2; exit 1; }
[[ -z $ENV_FILE || -r $ENV_FILE ]] || { echo "--env-file not readable: $ENV_FILE" >&2; exit 1; }
[[ -n $ENV_FILE || -f $HOME/.claude/.credentials.json ]] ||
  { echo "Claude has no credentials: pass --env-file, or run 'claude' and /login first" >&2; exit 1; }

command -v systemctl >/dev/null || { echo "systemd is required" >&2; exit 1; }
sudo -v

REPO=$(cd "$(dirname "$0")/.." && pwd)
OPT=$HOME/.local/opt
BIN=$HOME/.local/bin
export PATH="$BIN:$OPT/node/bin:$PATH"
mkdir -p "$OPT" "$BIN" "$HOME/.cloudcli"
printf 'ENV_FILE=%q\nPORT=%q\nWORKSPACES_ROOT=%q\n' "$ENV_FILE" "$PORT" "$WORKSPACES_ROOT" >"$CONF"

# Node, at the major version in .nvmrc.
node_major=$(tr -dc 0-9 <"$REPO/.nvmrc")
if ! node -v 2>/dev/null | grep -q "^v$node_major\."; then
  arch=$(uname -m); arch=${arch/x86_64/x64}; arch=${arch/aarch64/arm64}
  url=https://nodejs.org/dist/latest-v$node_major.x
  tarball=$(curl -fsSL "$url/SHASUMS256.txt" | grep -o "node-v[0-9.]*-linux-$arch.tar.xz" | head -1)
  echo "Installing $tarball"
  curl -fsSL "$url/$tarball" | tar -xJ -C "$OPT"
  ln -sfn "$OPT/${tarball%.tar.xz}" "$OPT/node"
  for b in node npm npx; do ln -sfn "$OPT/node/bin/$b" "$BIN/$b"; done
fi

command -v claude >/dev/null || curl -fsSL https://claude.ai/install.sh | bash

# Build this checkout and install it the way npm users get it.
cd "$REPO"
npm ci
npm run build
pack_dir=$(mktemp -d)
npm pack --pack-destination "$pack_dir" >/dev/null
npm install -g --prefix "$OPT/npm-global" "$pack_dir"/*.tgz
rm -rf "$pack_dir"
ln -sfn "$OPT/npm-global/bin/cloudcli" "$BIN/cloudcli"

# The service sees only start.sh's PATH, so name where node and claude were found (nvm, say).
svc_path=$BIN:$(dirname "$(command -v node)"):$(dirname "$(command -v claude)")

source_env=${ENV_FILE:+"source $(printf %q "$ENV_FILE") 2>/dev/null"}
cat >"$HOME/.cloudcli/start.sh" <<EOF
#!/bin/bash
# Generated by scripts/install-service.sh; re-run that instead of editing this file.
export PATH=$(printf %q "$svc_path"):\$PATH
# 2>/dev/null: env files written for interactive shells may 'unalias claude', which fails here.
$source_env
export HOST=0.0.0.0 SERVER_PORT=$PORT
export WORKSPACES_ROOT=$(printf %q "$WORKSPACES_ROOT")
# 0 = never time out held background work: the Claude process lives until its work is done or /exit.
export BG_WAIT_CEILING_MS=0
cd ~
exec "$BIN/cloudcli" start
EOF
chmod +x "$HOME/.cloudcli/start.sh"

# Only groups this user holds now: SSH logins may get them via pam_group, which
# /etc/group does not list, and a systemd service only gets what the unit lists.
groups= mine=" $(id -nG) "
for g in video render kvm docker; do [[ $mine == *" $g "* ]] && groups+="$g "; done

# Paths are quoted: RequiresMountsFor= and ExecStart= split on spaces.
mounts=$(printf '"%s" ' "$HOME" "$WORKSPACES_ROOT" ${ENV_FILE:+"$ENV_FILE"})
sudo tee /etc/systemd/system/cloudcli.service >/dev/null <<EOF
[Unit]
Description=CloudCLI web UI for Claude Code ($(id -un))
After=network-online.target
Wants=network-online.target
RequiresMountsFor=$mounts

[Service]
Type=simple
User=$(id -un)
Group=$(id -gn)
SupplementaryGroups=$groups
ExecStart="$HOME/.cloudcli/start.sh"
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF
sudo systemctl daemon-reload
sudo systemctl enable cloudcli

# Claude sessions started from the web UI live in the service's cgroup; restarting
# right away would kill the one running this script before it can report.
if grep -q 'cloudcli\.service' /proc/self/cgroup; then
  sudo systemd-run --on-active=20 systemctl restart cloudcli
  echo "cloudcli restarts in 20s: http://localhost:$PORT"
else
  sudo systemctl restart cloudcli
  echo "cloudcli started: http://localhost:$PORT"
fi
